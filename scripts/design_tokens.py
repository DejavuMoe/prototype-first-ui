#!/usr/bin/env python3
"""Validate and build W3C DTCG design tokens; generate perceptual color ramps.

Standard library only. Commands:

  check     Validate structure, aliases, types and declared contrast pairs in
            every mode (for example light and dark).
  build     Emit CSS custom properties, flat JSON, an iOS asset catalog plus
            Swift constants, Android resources, and Flutter constants from one
            token source.
  ramp      Generate an OKLCH lightness ramp for one hue (DTCG JSON or CSS).
  contrast  Report the WCAG 2 contrast ratio of two colors or token paths.

Conventions beyond the DTCG format (other DTCG tools ignore them):

* A token's ``$value`` is its default-mode value. Other modes live in
  ``"$extensions": {"mode": {"dark": "{color.neutral.950}"}}``. A mode name
  ``axis:value`` (for example ``density:compact``) targets another attribute
  axis; plain names belong to the ``theme`` axis.
* Root ``"$extensions": {"contrast": [{"fg": "color.text.primary",
  "bg": "color.bg.surface", "min": 4.5}]}`` declares pairs checked per mode.
* ``--overlay dark=tokens.dark.json`` merges a per-mode file instead.

The checks are deterministic. They cannot judge whether a palette is
appropriate for a brand or whether a color pair is actually rendered together.
"""

