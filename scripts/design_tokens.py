def is_alias(value: object) -> bool:
    return isinstance(value, str) and bool(ALIAS.match(value))


def parse_dimension(value: object) -> Tuple[float, str]:
    if isinstance(value, dict):
        number, unit = value.get("value"), value.get("unit")
        if isinstance(number, (int, float)) and not isinstance(number, bool) and isinstance(unit, str):
            return float(number), unit
        raise ValueError("dimension object needs numeric value and string unit")
    if isinstance(value, (int, float)) and not isinstance(value, bool) and value == 0:
        return 0.0, "px"
    if isinstance(value, str):
        match = re.fullmatch(r"\s*(-?\d+(?:\.\d+)?)\s*([a-z%]*)\s*", value)
        if match and (match.group(2) or float(match.group(1)) == 0):
            return float(match.group(1)), match.group(2) or "px"
    raise ValueError("invalid dimension %r" % (value,))


def parse_duration_ms(value: object) -> float:
    if isinstance(value, dict):
        number, unit = value.get("value"), value.get("unit")
        if isinstance(number, (int, float)) and unit in {"ms", "s"}:
            return float(number) * (1000 if unit == "s" else 1)
        raise ValueError("duration object needs numeric value and unit ms or s")
    if isinstance(value, str):
        match = re.fullmatch(r"\s*(\d+(?:\.\d+)?)\s*(ms|s)\s*", value)
        if match:
            return float(match.group(1)) * (1000 if match.group(2) == "s" else 1)
    raise ValueError("invalid duration %r" % (value,))


def write_text_lf(path: Path, text: str) -> None:
    """Write UTF-8 text with LF line endings on every OS (Python 3.9 compatible)."""
    with open(str(path), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def number_text(value: float) -> str:
    text = ("%.4f" % value).rstrip("0").rstrip(".")
    return text if text not in {"", "-0"} else "0"


def validate_resolved(kind: Optional[str], value: object) -> Optional[str]:
    """Return an error message when a resolved value does not fit its type."""
    try:
        if kind == "color":
            parse_dtcg_color(value)
            if isinstance(value, str) and not value.strip().startswith("#"):
                return "non-DTCG color string %r (use hex or a colorSpace object)" % value
        elif kind == "dimension":
            _, unit = parse_dimension(value)
            if unit not in {"px", "rem", "em", "ch", "%", "vw", "vh", "pt", "dp", "sp"}:
                return "unsupported dimension unit %r" % unit
        elif kind == "duration":
            parse_duration_ms(value)
        elif kind == "number":
            if not isinstance(value, (int, float)) or isinstance(value, bool):
                return "number token needs a JSON number"
        elif kind == "fontFamily":
            if not (isinstance(value, str) and value.strip()) and not (
                isinstance(value, list) and value and all(isinstance(item, str) and item.strip() for item in value)
            ):
                return "fontFamily needs a string or non-empty string list"
        elif kind == "fontWeight":
            if isinstance(value, str):
                if value not in FONT_WEIGHTS:
                    return "unknown fontWeight keyword %r" % value
            elif not isinstance(value, (int, float)) or not 1 <= value <= 1000:
                return "fontWeight must be 1-1000 or a keyword"
        elif kind == "cubicBezier":
            if not (isinstance(value, list) and len(value) == 4 and all(isinstance(item, (int, float)) for item in value)):
                return "cubicBezier needs four numbers"
            if not (0 <= value[0] <= 1 and 0 <= value[2] <= 1):
                return "cubicBezier x coordinates must be within [0, 1]"
        elif kind == "shadow":
            layers = value if isinstance(value, list) else [value]
            for layer in layers:
                if not isinstance(layer, dict) or "color" not in layer:
                    return "shadow layers need color, offsetX, offsetY, blur and spread"
                parse_dtcg_color(layer["color"])
                for key in ("offsetX", "offsetY", "blur", "spread"):
                    parse_dimension(layer.get(key, 0))
        elif kind == "typography":
            if not isinstance(value, dict):
                return "typography needs an object"
            missing = [key for key in ("fontFamily", "fontSize", "fontWeight", "lineHeight") if key not in value]
            if missing:
                return "typography is missing %s" % ", ".join(missing)
            parse_dimension(value["fontSize"])
        elif kind == "border":
            if not isinstance(value, dict) or not {"color", "width", "style"} <= set(value):
                return "border needs color, width and style"
            parse_dtcg_color(value["color"])
            parse_dimension(value["width"])
        elif kind == "transition":
            if not isinstance(value, dict) or not {"duration", "timingFunction"} <= set(value):
                return "transition needs duration and timingFunction"
            parse_duration_ms(value["duration"])
        elif kind == "gradient":
            if not isinstance(value, list) or not value:
                return "gradient needs a list of stops"
            for stop in value:
                if not isinstance(stop, dict) or "color" not in stop or "position" not in stop:
                    return "gradient stops need color and position"
                parse_dtcg_color(stop["color"])
    except ValueError as exc:
        return str(exc)
    return None


def css_name(path: str, prefix: str = "") -> str:
    name = re.sub(r"[^a-zA-Z0-9-]+", "-", path.replace(".", "-")).strip("-").lower()
    return "--" + (prefix + "-" if prefix else "") + name


def css_font_family(value: object) -> str:
    names = value if isinstance(value, list) else [value]
    rendered = []
    for name in names:
        text = str(name).strip()
        if text.lower() in GENERIC_FONTS or re.fullmatch(r"[A-Za-z-]+", text):
            rendered.append(text)
        else:
            rendered.append('"%s"' % text.replace('"', '\\"'))
    return ", ".join(rendered)


def css_dimension(value: object) -> str:
    number, unit = parse_dimension(value)
    return "0" if number == 0 else number_text(number) + unit


def css_duration(value: object) -> str:
    return number_text(parse_duration_ms(value)) + "ms"


def css_cubic(value: object) -> str:
    if isinstance(value, str):
        return value
    return "cubic-bezier(%s)" % ", ".join(number_text(float(item)) for item in value)  # type: ignore[union-attr]


def css_font_weight(value: object) -> str:
    if isinstance(value, str):
        return str(FONT_WEIGHTS.get(value, value))
    return number_text(float(value))  # type: ignore[arg-type]


class CssFormatter:
    """Format token values as CSS, preserving aliases as var() references."""

    def __init__(self, tokens: TokenSet, prefix: str, resolve_aliases: bool) -> None:
        self.tokens = tokens
        self.prefix = prefix
        self.resolve_aliases = resolve_aliases

    def part(self, value: object, kind: Optional[str], mode: str) -> str:
        if isinstance(value, str):
            match = ALIAS.match(value)
            if match:
                target = match.group(1)
                if not self.resolve_aliases:
                    return "var(%s)" % css_name(target, self.prefix)
                value = self.tokens.resolve(target, mode)
                kind = kind or self.tokens.token_type(target)
        if kind == "color":
            return to_hex(parse_dtcg_color(value))
        if kind == "dimension":
            return css_dimension(value)
        if kind == "duration":
            return css_duration(value)
        if kind == "cubicBezier":
            return css_cubic(value)
        if kind == "fontFamily":
            return css_font_family(value)
        if kind == "fontWeight":
            return css_font_weight(value)
        if kind == "number":
            return number_text(float(value))  # type: ignore[arg-type]
        if kind == "shadow":
            layers = value if isinstance(value, list) else [value]
            rendered = []
            for layer in layers:
                assert isinstance(layer, dict)
                pieces = ["inset"] if layer.get("inset") else []
                for key in ("offsetX", "offsetY", "blur", "spread"):
                    pieces.append(self.part(layer.get(key, 0), "dimension", mode))
                pieces.append(self.part(layer["color"], "color", mode))
                rendered.append(" ".join(pieces))
            return ", ".join(rendered)
        if kind == "border":
            assert isinstance(value, dict)
            style = value.get("style")
            style_text = style if isinstance(style, str) else "solid"
            return "%s %s %s" % (
                self.part(value["width"], "dimension", mode),
                style_text,
                self.part(value["color"], "color", mode),
            )
        if kind == "transition":
            assert isinstance(value, dict)
            pieces = [self.part(value["duration"], "duration", mode), self.part(value["timingFunction"], "cubicBezier", mode)]
            if "delay" in value:
                pieces.append(self.part(value["delay"], "duration", mode))
            return " ".join(pieces)
        if kind == "gradient":
            assert isinstance(value, list)
            return ", ".join(
                "%s %s%%" % (self.part(stop["color"], "color", mode), number_text(float(stop["position"]) * 100)) for stop in value
            )
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            return number_text(float(value))
        return str(value)

    def entries(self, token: Token, mode: str) -> List[Tuple[str, str]]:
        kind = self.tokens.token_type(token.path)
        raw = self.tokens.raw(token.path, mode)
        name = css_name(token.path, self.prefix)
        if kind == "typography" and not is_alias(raw):
            assert isinstance(raw, dict)
            parts = []
            mapping = (
                ("fontFamily", "font-family", "fontFamily"),
                ("fontSize", "font-size", "dimension"),
                ("fontWeight", "font-weight", "fontWeight"),
                ("lineHeight", "line-height", "number"),
                ("letterSpacing", "letter-spacing", "dimension"),
            )
            for key, suffix, sub_kind in mapping:
                if key in raw:
                    sub_value = raw[key]
                    if key == "lineHeight" and not is_alias(sub_value) and isinstance(sub_value, str):
                        parts.append((name + "-" + suffix, sub_value))
                    else:
                        parts.append((name + "-" + suffix, self.part(sub_value, sub_kind, mode)))
            return parts
        return [(name, self.part(raw, kind, mode))]


