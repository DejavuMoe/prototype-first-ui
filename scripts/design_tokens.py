DEFAULT_STEPS = (50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950)
DEFAULT_LIGHTNESS = {
    50: 0.975, 100: 0.945, 200: 0.895, 300: 0.825, 400: 0.725, 500: 0.635,
    600: 0.555, 700: 0.475, 800: 0.395, 900: 0.315, 950: 0.245,
}
CHROMA_SHAPE = {
    50: 0.14, 100: 0.24, 200: 0.42, 300: 0.66, 400: 0.88, 500: 1.0,
    600: 1.0, 700: 0.92, 800: 0.78, 900: 0.56, 950: 0.36,
}


def interpolate(table: Dict[int, float], step: int) -> float:
    keys = sorted(table)
    if step <= keys[0]:
        return table[keys[0]]
    if step >= keys[-1]:
        return table[keys[-1]]
    for low, high in zip(keys, keys[1:]):
        if low <= step <= high:
            fraction = (step - low) / (high - low)
            return table[low] + (table[high] - table[low]) * fraction
    return table[keys[-1]]


def generate_ramp(hue: float, chroma: float, steps: Sequence[int] = DEFAULT_STEPS, hue_shift: float = 0.0, lightness: Optional[Dict[int, float]] = None) -> List[Dict[str, object]]:
    table = lightness or DEFAULT_LIGHTNESS
    ordered = sorted(steps)
    result = []
    for index, step in enumerate(ordered):
        position = index / max(1, len(ordered) - 1)
        step_hue = (hue + hue_shift * (position - 0.5) * 2) % 360
        target_l = table[step] if step in table else interpolate(table, step)
        target_c = chroma * interpolate(CHROMA_SHAPE, step)
        rgb, used = gamut_map_oklch(target_l, target_c, step_hue)
        result.append({"step": step, "hex": to_hex(list(rgb) + [1.0]), "l": target_l, "c": used, "h": step_hue})
    return result


