def load_token_set(path: Path, overlays: Sequence[str]) -> TokenSet:
    token_set = TokenSet(path.name)
    try:
        token_set.load(json.loads(path.read_text(encoding="utf-8")))
    except (OSError, json.JSONDecodeError) as exc:
        token_set.errors.append("Cannot read %s: %s" % (path, exc))
        return token_set
    for overlay in overlays:
        if "=" not in overlay:
            token_set.errors.append("Overlay must be MODE=PATH: %s" % overlay)
            continue
        mode, overlay_path = overlay.split("=", 1)
        try:
            data = json.loads(Path(overlay_path).read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            token_set.errors.append("Cannot read overlay %s: %s" % (overlay_path, exc))
            continue
        token_set.apply_overlay(mode.strip(), data, Path(overlay_path).name)
    return token_set


def validate_token_set(token_set: TokenSet) -> None:
    if not token_set.tokens and not token_set.errors:
        token_set.errors.append("No tokens found (a token is an object with $value)")
    for path in sorted(token_set.tokens):
        token = token_set.tokens[path]
        kind = token_set.token_type(path)
        if kind is None and not token.declared_type:
            token_set.errors.append("%s: $type is missing and cannot be inferred from an alias" % path)
        declared = token.declared_type
        for mode in [DEFAULT_MODE] + sorted(token.modes):
            raw = token.value if mode == DEFAULT_MODE else token.modes[mode]
            label = path if mode == DEFAULT_MODE else "%s [%s]" % (path, mode)
            match = ALIAS.match(raw) if isinstance(raw, str) else None
            if match:
                target = match.group(1)
                if target not in token_set.tokens:
                    token_set.errors.append("%s: unknown reference {%s}" % (label, target))
                    continue
                target_type = token_set.token_type(target)
                if declared and target_type and declared != target_type:
                    token_set.errors.append("%s: %s token aliases %s token {%s}" % (label, declared, target_type, target))
            try:
                resolved = token_set.resolve(path, mode)
            except ValueError as exc:
                token_set.errors.append("%s: %s" % (label, exc))
                continue
            if kind in KNOWN_TYPES:
                problem = validate_resolved(kind, resolved)
                if problem:
                    if problem.startswith("non-DTCG"):
                        token_set.warnings.append("%s: %s" % (label, problem))
                    else:
                        token_set.errors.append("%s: %s" % (label, problem))
        if isinstance(token.value, str) and kind == "color" and not ALIAS.match(token.value):
            parsed = parse_css_color(token.value)
            if parsed is not None and parsed[3] < 1 and "overlay" not in path and "scrim" not in path and "shadow" not in path:
                token_set.warnings.append("%s: translucent color; contrast depends on what is behind it" % path)


def contrast_rules(token_set: TokenSet) -> List[Dict[str, object]]:
    rules = token_set.extensions.get("contrast", [])
    if not isinstance(rules, list):
        token_set.errors.append("$extensions.contrast must be a list")
        return []
    valid: List[Dict[str, object]] = []
    for index, rule in enumerate(rules):
        if not isinstance(rule, dict) or not isinstance(rule.get("fg"), str) or not isinstance(rule.get("bg"), str):
            token_set.errors.append("$extensions.contrast[%d] needs fg and bg token paths" % index)
            continue
        minimum = rule.get("min", 4.5)
        if not isinstance(minimum, (int, float)) or minimum < 1:
            token_set.errors.append("$extensions.contrast[%d].min must be a ratio >= 1" % index)
            continue
        for key in ("fg", "bg", "over"):
            target = rule.get(key)
            if target is not None and (not isinstance(target, str) or target not in token_set.tokens):
                token_set.errors.append("$extensions.contrast[%d].%s references unknown token %r" % (index, key, target))
                break
        else:
            valid.append(rule)
    return valid


def theme_modes(token_set: TokenSet) -> List[str]:
    return [mode for mode in token_set.modes() if ":" not in mode]


def evaluate_contrast(token_set: TokenSet) -> List[Dict[str, object]]:
    results: List[Dict[str, object]] = []
    for rule in contrast_rules(token_set):
        for mode in theme_modes(token_set):
            entry: Dict[str, object] = {
                "fg": rule["fg"],
                "bg": rule["bg"],
                "mode": mode,
                "min": float(rule.get("min", 4.5)),  # type: ignore[arg-type]
                "label": rule.get("label"),
            }
            try:
                foreground = token_set.color(str(rule["fg"]), mode)
                background = token_set.color(str(rule["bg"]), mode)
                if background[3] < 1:
                    over = rule.get("over")
                    if not isinstance(over, str):
                        entry.update({"ratio": None, "status": "error", "detail": "translucent background needs an 'over' token"})
                        results.append(entry)
                        continue
                    background = composite(background, token_set.color(over, mode))
                ratio = contrast_ratio(foreground, background)
            except ValueError as exc:
                entry.update({"ratio": None, "status": "error", "detail": str(exc)})
                results.append(entry)
                continue
            entry["ratio"] = round(ratio, 2)
            entry["status"] = "pass" if ratio + 1e-9 >= float(entry["min"]) else "fail"  # type: ignore[arg-type]
            results.append(entry)
    return results


def summarize_types(token_set: TokenSet) -> Dict[str, int]:
    counts: Dict[str, int] = {}
    for path in token_set.tokens:
        kind = token_set.token_type(path) or "unknown"
        counts[kind] = counts.get(kind, 0) + 1
    return dict(sorted(counts.items()))


def check_tokens(path: Path, overlays: Sequence[str] = ()) -> Dict[str, object]:
    token_set = load_token_set(path, overlays)
    if not token_set.errors:
        validate_token_set(token_set)
    contrast = evaluate_contrast(token_set) if not token_set.errors else []
    failures = [item for item in contrast if item["status"] != "pass"]
    return {
        "schemaVersion": 1,
        "source": str(path),
        "tokens": len(token_set.tokens),
        "types": summarize_types(token_set),
        "modes": token_set.modes(),
        "errors": token_set.errors,
        "warnings": token_set.warnings,
        "contrast": contrast,
        "passed": not token_set.errors and not failures,
        "limitations": [
            "Contrast is checked only for declared pairs; undeclared combinations are not inferred.",
            "WCAG 2 ratios do not measure font weight/size, anti-aliasing, or perceptual APCA contrast.",
        ],
    }


def print_check(report: Dict[str, object]) -> None:
    print("Tokens: %s in %s (%s)" % (report["tokens"], report["source"], ", ".join("%s %d" % item for item in report["types"].items())))  # type: ignore[union-attr]
    print("Modes: %s" % ", ".join(report["modes"]))  # type: ignore[arg-type]
    for warning in report["warnings"]:  # type: ignore[union-attr]
        print("WARNING: %s" % warning, file=sys.stderr)
    for error in report["errors"]:  # type: ignore[union-attr]
        print("ERROR: %s" % error, file=sys.stderr)
    contrast = report["contrast"]
    if contrast:
        print("Contrast (WCAG 2, declared pairs):")
        for item in contrast:  # type: ignore[union-attr]
            ratio = "n/a" if item["ratio"] is None else "%.2f:1" % item["ratio"]
            detail = (" - %s" % item["detail"]) if item.get("detail") else ""
            print("  %-4s %-8s %s on %s  %s (min %s)%s" % (
                str(item["status"]).upper(), item["mode"], item["fg"], item["bg"], ratio, number_text(item["min"]), detail,
            ))
    elif not report["errors"]:
        print("Contrast: no pairs declared in $extensions.contrast (nothing checked).")
    failures = [item for item in contrast if item["status"] != "pass"]  # type: ignore[union-attr]
    if report["passed"]:
        print("Token check passed.")
    else:
        print("Token check failed: %d errors, %d contrast failures." % (len(report["errors"]), len(failures)), file=sys.stderr)  # type: ignore[arg-type]


