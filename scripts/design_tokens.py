class Token:
    __slots__ = ("path", "declared_type", "value", "modes", "description", "deprecated")

    def __init__(self, path: str, declared_type: Optional[str], value: object, modes: Dict[str, object], description: Optional[str], deprecated: object) -> None:
        self.path = path
        self.declared_type = declared_type
        self.value = value
        self.modes = modes
        self.description = description
        self.deprecated = deprecated


class TokenSet:
    def __init__(self, source: str) -> None:
        self.source = source
        self.tokens: Dict[str, Token] = {}
        self.extensions: Dict[str, object] = {}
        self.errors: List[str] = []
        self.warnings: List[str] = []

    # -- loading -----------------------------------------------------------

    def load(self, data: object) -> None:
        if not isinstance(data, dict):
            self.errors.append("Token file must contain a JSON object")
            return
        extensions = data.get("$extensions")
        if isinstance(extensions, dict):
            self.extensions = extensions
        self._walk(data, [], None)

    def _walk(self, node: Dict[str, object], parts: List[str], inherited: Optional[str]) -> None:
        group_type = node.get("$type", inherited)
        if "$type" in node and not isinstance(node["$type"], str):
            self.errors.append("%s: $type must be a string" % (".".join(parts) or "(root)"))
            group_type = inherited
        for key, child in node.items():
            if key.startswith("$"):
                if key == "$root" and isinstance(child, dict) and "$value" in child and parts:
                    self._add_token(parts, child, group_type)
                elif key not in GROUP_PROPS:
                    self.warnings.append("%s: unsupported group property %s ignored" % (".".join(parts) or "(root)", key))
                continue
            label = ".".join(parts + [key])
            if any(character in key for character in ".{}") or not key.strip():
                self.errors.append("%s: token and group names must not contain '.', '{' or '}'" % label)
                continue
            if not isinstance(child, dict):
                self.errors.append("%s: expected a token or group object" % label)
                continue
            if "$value" in child:
                self._add_token(parts + [key], child, group_type)
            else:
                self._walk(child, parts + [key], group_type)  # type: ignore[arg-type]

    def _add_token(self, parts: List[str], node: Dict[str, object], inherited: Optional[str]) -> None:
        path = ".".join(parts)
        for key in node:
            if key.startswith("$") and key not in TOKEN_PROPS:
                self.warnings.append("%s: unsupported token property %s ignored" % (path, key))
            elif not key.startswith("$"):
                self.errors.append("%s: a token cannot contain child %r" % (path, key))
        declared = node.get("$type", inherited)
        if declared is not None and not isinstance(declared, str):
            self.errors.append("%s: $type must be a string" % path)
            declared = None
        if isinstance(declared, str) and declared not in KNOWN_TYPES:
            self.warnings.append("%s: unknown $type %r is passed through unvalidated" % (path, declared))
        modes: Dict[str, object] = {}
        extensions = node.get("$extensions")
        if isinstance(extensions, dict) and "mode" in extensions:
            raw_modes = extensions["mode"]
            if not isinstance(raw_modes, dict) or not all(isinstance(name, str) and name.strip() for name in raw_modes):
                self.errors.append("%s: $extensions.mode must map mode names to values" % path)
            else:
                modes = dict(raw_modes)
                if DEFAULT_MODE in modes:
                    self.errors.append("%s: mode name %r is reserved for $value" % (path, DEFAULT_MODE))
        description = node.get("$description")
        if description is not None and not isinstance(description, str):
            self.errors.append("%s: $description must be a string" % path)
            description = None
        if path in self.tokens:
            self.errors.append("%s: duplicate token path" % path)
        self.tokens[path] = Token(path, declared, node.get("$value"), modes, description, node.get("$deprecated"))

    def apply_overlay(self, mode: str, data: object, label: str) -> None:
        overlay = TokenSet(label)
        overlay.load(data)
        self.errors.extend("%s: %s" % (label, message) for message in overlay.errors)
        for path, token in overlay.tokens.items():
            if path not in self.tokens:
                self.errors.append("%s: overlay token %s does not exist in the base set" % (label, path))
                continue
            self.tokens[path].modes[mode] = token.value

    # -- queries -----------------------------------------------------------

    def modes(self) -> List[str]:
        names: Set[str] = set()
        for token in self.tokens.values():
            names.update(token.modes)
        return [DEFAULT_MODE] + sorted(names)

    def raw(self, path: str, mode: str) -> object:
        """Value for a mode; tokens without that mode fall back to $value."""
        token = self.tokens[path]
        if mode != DEFAULT_MODE and mode in token.modes:
            return token.modes[mode]
        return token.value

    def token_type(self, path: str, stack: Tuple[str, ...] = ()) -> Optional[str]:
        token = self.tokens.get(path)
        if token is None:
            return None
        if token.declared_type:
            return token.declared_type
        if path in stack:
            return None
        if isinstance(token.value, str):
            match = ALIAS.match(token.value)
            if match:
                return self.token_type(match.group(1), stack + (path,))
        return None

    def resolve(self, path: str, mode: str, stack: Tuple[str, ...] = ()) -> object:
        if path in stack:
            raise ValueError("alias cycle: %s" % " -> ".join(stack + (path,)))
        if path not in self.tokens:
            raise ValueError("unknown token reference {%s}" % path)
        return self.resolve_value(self.raw(path, mode), mode, stack + (path,))

    def resolve_value(self, value: object, mode: str, stack: Tuple[str, ...] = ()) -> object:
        if isinstance(value, str):
            match = ALIAS.match(value)
            if match:
                return self.resolve(match.group(1), mode, stack)
            return value
        if isinstance(value, list):
            return [self.resolve_value(item, mode, stack) for item in value]
        if isinstance(value, dict):
            return {key: self.resolve_value(item, mode, stack) for key, item in value.items()}
        return value

    def color(self, path: str, mode: str) -> RGBA:
        return parse_dtcg_color(self.resolve(path, mode))


