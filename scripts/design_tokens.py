def mode_selector(mode: str) -> Tuple[str, Optional[str]]:
    axis, _, value = mode.partition(":") if ":" in mode else ("theme", "", mode)
    selector = ':root[data-%s="%s"]' % (axis, value)
    media = "(prefers-color-scheme: dark)" if axis == "theme" and value == "dark" else None
    return selector, media


def build_css(token_set: TokenSet, source_label: str, prefix: str = "", resolve_aliases: bool = False) -> str:
    formatter = CssFormatter(token_set, prefix, resolve_aliases)
    modes = token_set.modes()
    has_dark = "dark" in modes
    options = "".join([" --prefix %s" % prefix if prefix else "", " --resolve" if resolve_aliases else ""])
    header = GENERATED_NOTE % source_label + (" Options:%s" % options if options else "")
    lines = ["/* %s */" % header, ":root {"]
    if has_dark:
        lines.append("  color-scheme: light;")
    for path in list(token_set.tokens):
        for name, value in formatter.entries(token_set.tokens[path], DEFAULT_MODE):
            lines.append("  %s: %s;" % (name, value))
    lines.append("}")
    for mode in modes[1:]:
        changed = [
            path
            for path in list(token_set.tokens)
            if (mode in token_set.tokens[path].modes and token_set.tokens[path].modes[mode] != token_set.tokens[path].value)
            or (resolve_aliases and normalized(token_set, path, mode) != normalized(token_set, path, DEFAULT_MODE))
        ]
        if not changed:
            continue
        body: List[str] = []
        if mode == "dark":
            body.append("color-scheme: dark;")
        for path in changed:
            for name, value in formatter.entries(token_set.tokens[path], mode):
                body.append("%s: %s;" % (name, value))
        selector, media = mode_selector(mode)
        lines.append("")
        lines.append(selector + " {")
        lines.extend("  " + entry for entry in body)
        lines.append("}")
        if media:
            lines.append("@media %s {" % media)
            lines.append("  :root:not([data-theme]) {")
            lines.extend("    " + entry for entry in body)
            lines.append("  }")
            lines.append("}")
    return "\n".join(lines) + "\n"


def normalized(token_set: TokenSet, path: str, mode: str) -> object:
    kind = token_set.token_type(path)
    value = token_set.resolve(path, mode)
    formatter = CssFormatter(token_set, "", True)
    if kind in {"color", "dimension", "duration", "cubicBezier", "fontFamily", "fontWeight", "number", "shadow", "border", "transition", "gradient"}:
        return formatter.part(value, kind, mode)
    if kind == "typography" and isinstance(value, dict):
        return {
            key: formatter.part(item, {"fontFamily": "fontFamily", "fontSize": "dimension", "fontWeight": "fontWeight", "letterSpacing": "dimension"}.get(key), mode)
            for key, item in value.items()
        }
    return value


def build_json(token_set: TokenSet, source_label: str) -> str:
    output: Dict[str, object] = {"$generated": GENERATED_NOTE % source_label, "modes": {}}
    for mode in token_set.modes():
        output["modes"][mode] = {path: normalized(token_set, path, mode) for path in list(token_set.tokens)}  # type: ignore[index]
    return json.dumps(output, ensure_ascii=False, indent=2) + "\n"


