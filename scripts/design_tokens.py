def srgb_to_linear(value: float) -> float:
    sign = -1.0 if value < 0 else 1.0
    magnitude = abs(value)
    if magnitude <= 0.04045:
        return value / 12.92
    return sign * ((magnitude + 0.055) / 1.055) ** 2.4


def linear_to_srgb(value: float) -> float:
    sign = -1.0 if value < 0 else 1.0
    magnitude = abs(value)
    if magnitude <= 0.0031308:
        return value * 12.92
    return sign * (1.055 * magnitude ** (1 / 2.4) - 0.055)


def oklab_to_linear_srgb(lightness: float, a: float, b: float) -> Tuple[float, float, float]:
    l_ = lightness + 0.3963377774 * a + 0.2158037573 * b
    m_ = lightness - 0.1055613458 * a - 0.0638541728 * b
    s_ = lightness - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    return (
        4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
        -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
        -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s,
    )


def linear_srgb_to_oklab(r: float, g: float, b: float) -> Tuple[float, float, float]:
    l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b
    m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b
    s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b
    l_, m_, s_ = (math.copysign(abs(v) ** (1 / 3), v) for v in (l, m, s))
    return (
        0.2104542553 * l_ + 0.7936177850 * m_ - 0.0040720468 * s_,
        1.9779984951 * l_ - 2.4285922050 * m_ + 0.4505937099 * s_,
        0.0259040371 * l_ + 0.7827717662 * m_ - 0.8086757660 * s_,
    )


def oklch_to_srgb(lightness: float, chroma: float, hue: float) -> Tuple[float, float, float]:
    radians = math.radians(hue)
    linear = oklab_to_linear_srgb(lightness, chroma * math.cos(radians), chroma * math.sin(radians))
    return tuple(linear_to_srgb(channel) for channel in linear)  # type: ignore[return-value]


def srgb_to_oklch(rgb: Sequence[float]) -> Tuple[float, float, float]:
    lightness, a, b = linear_srgb_to_oklab(*(srgb_to_linear(channel) for channel in rgb[:3]))
    chroma = math.hypot(a, b)
    hue = math.degrees(math.atan2(b, a)) % 360 if chroma > 1e-7 else 0.0
    return lightness, chroma, hue


def in_gamut(rgb: Sequence[float], epsilon: float = 1e-6) -> bool:
    return all(-epsilon <= channel <= 1 + epsilon for channel in rgb[:3])


def gamut_map_oklch(lightness: float, chroma: float, hue: float) -> Tuple[Tuple[float, float, float], float]:
    """Reduce chroma at constant lightness and hue until the color fits sRGB."""
    lightness = min(1.0, max(0.0, lightness))
    rgb = oklch_to_srgb(lightness, chroma, hue)
    if in_gamut(rgb):
        return rgb, chroma
    low, high = 0.0, chroma
    for _ in range(40):
        middle = (low + high) / 2
        if in_gamut(oklch_to_srgb(lightness, middle, hue)):
            low = middle
        else:
            high = middle
    return oklch_to_srgb(lightness, low, hue), low


def hsl_to_srgb(hue: float, saturation: float, lightness: float) -> Tuple[float, float, float]:
    hue = hue % 360
    saturation = min(1.0, max(0.0, saturation))
    lightness = min(1.0, max(0.0, lightness))

    def channel(n: float) -> float:
        k = (n + hue / 30) % 12
        a = saturation * min(lightness, 1 - lightness)
        return lightness - a * max(-1.0, min(k - 3, 9 - k, 1.0))

    return channel(0), channel(8), channel(4)


def hwb_to_srgb(hue: float, whiteness: float, blackness: float) -> Tuple[float, float, float]:
    if whiteness + blackness >= 1:
        gray = whiteness / (whiteness + blackness)
        return gray, gray, gray
    base = hsl_to_srgb(hue, 1.0, 0.5)
    return tuple(channel * (1 - whiteness - blackness) + whiteness for channel in base)  # type: ignore[return-value]


P3_TO_XYZ = (
    (0.4865709486482162, 0.26566769316909306, 0.1982172852343625),
    (0.2289745640697488, 0.6917385218365064, 0.079286914093745),
    (0.0, 0.04511338185890264, 1.043944368900976),
)
XYZ_TO_LINEAR_SRGB = (
    (3.2409699419045226, -1.537383177570094, -0.4986107602930034),
    (-0.9692436362808796, 1.8759675015077202, 0.04155505740717559),
    (0.05563007969699366, -0.20397695888897652, 1.0569715142428786),
)


def _matrix(rows: Sequence[Sequence[float]], vector: Sequence[float]) -> Tuple[float, float, float]:
    return tuple(sum(row[index] * vector[index] for index in range(3)) for row in rows)  # type: ignore[return-value]


def display_p3_to_srgb(r: float, g: float, b: float) -> Tuple[float, float, float]:
    xyz = _matrix(P3_TO_XYZ, [srgb_to_linear(value) for value in (r, g, b)])
    return tuple(linear_to_srgb(value) for value in _matrix(XYZ_TO_LINEAR_SRGB, xyz))  # type: ignore[return-value]


def clamp_rgba(rgba: Sequence[float]) -> RGBA:
    r, g, b = (min(1.0, max(0.0, value)) for value in rgba[:3])
    alpha = min(1.0, max(0.0, rgba[3] if len(rgba) > 3 else 1.0))
    return r, g, b, alpha


def to_hex(rgba: Sequence[float]) -> str:
    r, g, b, alpha = clamp_rgba(rgba)
    channels = [int(round(value * 255)) for value in (r, g, b)]
    text = "#" + "".join("%02x" % value for value in channels)
    if alpha < 1 - 1e-6:
        text += "%02x" % int(round(alpha * 255))
    return text


def relative_luminance(rgba: Sequence[float]) -> float:
    r, g, b, _ = clamp_rgba(rgba)
    return 0.2126 * srgb_to_linear(r) + 0.7152 * srgb_to_linear(g) + 0.0722 * srgb_to_linear(b)


def composite(foreground: Sequence[float], background: Sequence[float]) -> RGBA:
    fr, fg, fb, fa = clamp_rgba(foreground)
    br, bg, bb, ba = clamp_rgba(background)
    alpha = fa + ba * (1 - fa)
    if alpha <= 0:
        return 0.0, 0.0, 0.0, 0.0
    mix = lambda front, back: (front * fa + back * ba * (1 - fa)) / alpha  # noqa: E731
    return mix(fr, br), mix(fg, bg), mix(fb, bb), alpha


def contrast_ratio(foreground: Sequence[float], background: Sequence[float]) -> float:
    """WCAG 2 contrast ratio; a translucent foreground is composited first."""
    back = clamp_rgba(background)
    front = composite(foreground, back) if clamp_rgba(foreground)[3] < 1 else clamp_rgba(foreground)
    lighter, darker = sorted((relative_luminance(front), relative_luminance(back)), reverse=True)
    return (lighter + 0.05) / (darker + 0.05)


def _parse_number(token: str, percent_scale: float = 1.0) -> float:
    token = token.strip().lower()
    if token == "none":
        return 0.0
    if token.endswith("%"):
        return float(token[:-1]) / 100 * percent_scale
    return float(token)


def _parse_hue(token: str) -> float:
    token = token.strip().lower()
    if token == "none":
        return 0.0
    for suffix, factor in (("deg", 1.0), ("grad", 0.9), ("rad", 180 / math.pi), ("turn", 360.0)):
        if token.endswith(suffix):
            return float(token[: -len(suffix)]) * factor
    return float(token)


def _components(body: str) -> Tuple[List[str], Optional[str]]:
    alpha: Optional[str] = None
    if "/" in body:
        body, alpha = body.split("/", 1)
    parts = [part for part in re.split(r"[\s,]+", body.strip()) if part]
    if alpha is None and len(parts) == 4:
        alpha = parts.pop()
    return parts, alpha.strip() if alpha else None


def parse_css_color(text: str) -> Optional[RGBA]:
    """Parse common CSS color syntaxes. Returns None for unknown or dynamic values."""
    value = text.strip().lower()
    if not value:
        return None
    if value == "transparent":
        return 0.0, 0.0, 0.0, 0.0
    if value in NAMED_COLORS:
        value = "#" + NAMED_COLORS[value]
    if value.startswith("#"):
        digits = value[1:]
        if not re.fullmatch(r"[0-9a-f]{3,8}", digits) or len(digits) not in {3, 4, 6, 8}:
            return None
        if len(digits) in {3, 4}:
            digits = "".join(character * 2 for character in digits)
        channels = [int(digits[index : index + 2], 16) / 255 for index in range(0, len(digits), 2)]
        if len(channels) == 3:
            channels.append(1.0)
        return clamp_rgba(channels)
    match = re.fullmatch(r"([a-z-]+)\((.*)\)", value)
    if not match:
        return None
    function, body = match.groups()
    if "var(" in body or "calc(" in body or "from " in body:
        return None
    try:
        parts, alpha_text = _components(body)
        alpha = _parse_number(alpha_text) if alpha_text else 1.0
        if function in {"rgb", "rgba"} and len(parts) == 3:
            rgb = [_parse_number(part, 255.0) / 255 for part in parts]
            return clamp_rgba(rgb + [alpha])
        if function in {"hsl", "hsla"} and len(parts) == 3:
            saturation = _parse_number(parts[1] if parts[1].endswith("%") else parts[1] + "%")
            lightness = _parse_number(parts[2] if parts[2].endswith("%") else parts[2] + "%")
            return clamp_rgba(list(hsl_to_srgb(_parse_hue(parts[0]), saturation, lightness)) + [alpha])
        if function == "hwb" and len(parts) == 3:
            whiteness = _parse_number(parts[1] if parts[1].endswith("%") else parts[1] + "%")
            blackness = _parse_number(parts[2] if parts[2].endswith("%") else parts[2] + "%")
            return clamp_rgba(list(hwb_to_srgb(_parse_hue(parts[0]), whiteness, blackness)) + [alpha])
        if function == "oklch" and len(parts) == 3:
            rgb, _ = gamut_map_oklch(_parse_number(parts[0]), _parse_number(parts[1], 0.4), _parse_hue(parts[2]))
            return clamp_rgba(list(rgb) + [alpha])
        if function == "oklab" and len(parts) == 3:
            linear = oklab_to_linear_srgb(_parse_number(parts[0]), _parse_number(parts[1], 0.4), _parse_number(parts[2], 0.4))
            return clamp_rgba([linear_to_srgb(channel) for channel in linear] + [alpha])
        if function == "color" and len(parts) == 4:
            space, channels = parts[0], [_parse_number(part) for part in parts[1:]]
            if space == "srgb":
                return clamp_rgba(channels + [alpha])
            if space == "srgb-linear":
                return clamp_rgba([linear_to_srgb(channel) for channel in channels] + [alpha])
            if space == "display-p3":
                return clamp_rgba(list(display_p3_to_srgb(*channels)) + [alpha])
    except (ValueError, IndexError):
        return None
    return None


def parse_dtcg_color(value: object) -> RGBA:
    """Parse a DTCG color value: a hex string (draft format) or a color object."""
    if isinstance(value, str):
        parsed = parse_css_color(value)
        if parsed is None:
            raise ValueError("unsupported color string %r" % value)
        return parsed
    if not isinstance(value, dict):
        raise ValueError("color value must be a hex string or a colorSpace object")
    space = value.get("colorSpace")
    components = value.get("components")
    alpha_value = value.get("alpha", 1)
    alpha = float(alpha_value) if isinstance(alpha_value, (int, float)) else 1.0
    if isinstance(components, list) and len(components) == 3:
        numbers = [0.0 if item == "none" else float(item) for item in components if isinstance(item, (int, float)) or item == "none"]
        if len(numbers) == 3:
            if space == "srgb":
                return clamp_rgba(numbers + [alpha])
            if space == "srgb-linear":
                return clamp_rgba([linear_to_srgb(item) for item in numbers] + [alpha])
            if space == "hsl":
                return clamp_rgba(list(hsl_to_srgb(numbers[0], numbers[1] / 100, numbers[2] / 100)) + [alpha])
            if space == "hwb":
                return clamp_rgba(list(hwb_to_srgb(numbers[0], numbers[1] / 100, numbers[2] / 100)) + [alpha])
            if space == "oklch":
                rgb, _ = gamut_map_oklch(*numbers)
                return clamp_rgba(list(rgb) + [alpha])
            if space == "oklab":
                return clamp_rgba([linear_to_srgb(item) for item in oklab_to_linear_srgb(*numbers)] + [alpha])
            if space == "display-p3":
                return clamp_rgba(list(display_p3_to_srgb(*numbers)) + [alpha])
    fallback = value.get("hex")
    if isinstance(fallback, str):
        parsed = parse_css_color(fallback)
        if parsed is not None:
            return clamp_rgba(parsed[:3] + (alpha,))
    raise ValueError("unsupported colorSpace %r without a usable hex fallback" % space)


