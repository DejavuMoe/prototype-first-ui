DEFAULT_TOKEN_FILES = (Path("designs") / "system" / "tokens.json", Path("tokens.json"))


def token_source(value: Optional[str]) -> Optional[Path]:
    """The given token file, else designs/system/tokens.json, else ./tokens.json."""
    if value:
        return Path(value)
    for candidate in DEFAULT_TOKEN_FILES:
        if candidate.is_file():
            return candidate
    print("ERROR: no token file given and none found at %s" % " or ".join(path.as_posix() for path in DEFAULT_TOKEN_FILES), file=sys.stderr)
    return None


def cmd_check(args: argparse.Namespace) -> int:
    source = token_source(args.tokens)
    if source is None:
        return 2
    report = check_tokens(source, args.overlay)
    if args.json:
        print(json.dumps(report, ensure_ascii=True, indent=2))
    else:
        print_check(report)
    return 0 if report["passed"] else 1


def cmd_build(args: argparse.Namespace) -> int:
    formats = [item.strip() for item in args.format.split(",") if item.strip()]
    unknown = [item for item in formats if item not in FORMATS]
    if unknown:
        print("ERROR: unknown format(s) %s; choose from %s" % (", ".join(unknown), ", ".join(FORMATS)), file=sys.stderr)
        return 2
    source = token_source(args.tokens)
    if source is None:
        return 2
    output = Path(args.out) if args.out else source.parent
    try:
        written, report = build_tokens(source, output, formats, args.overlay, args.prefix, args.resolve, args.css_name)
    except ValueError as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        return 1
    if report["errors"]:
        print_check(report)
        print("Build skipped because the token source is invalid.", file=sys.stderr)
        return 1
    for path in written:
        print("Wrote %s" % path)
    failures = [item for item in report["contrast"] if item["status"] != "pass"]  # type: ignore[union-attr]
    if failures:
        print("WARNING: %d declared contrast pair(s) fail; run check for details." % len(failures), file=sys.stderr)
    return 0


def cmd_ramp(args: argparse.Namespace) -> int:
    steps = [int(item) for item in args.steps.split(",")] if args.steps else list(DEFAULT_STEPS)
    ramp = generate_ramp(args.hue, args.chroma, steps, args.hue_shift)
    if args.format == "css":
        for entry in ramp:
            print("--%s-%s: %s; /* oklch(%.3f %.3f %.1f) */" % (args.name, entry["step"], entry["hex"], entry["l"], entry["c"], entry["h"]))
        return 0
    group: Dict[str, object] = {"$type": "color"}
    for entry in ramp:
        group[str(entry["step"])] = {"$value": entry["hex"], "$description": "oklch(%.3f %.3f %.1f)" % (entry["l"], entry["c"], entry["h"])}
    print(json.dumps({args.name: group}, indent=2))
    return 0


def resolve_color_argument(value: str, token_set: Optional[TokenSet], mode: str) -> RGBA:
    if token_set is not None and value in token_set.tokens:
        return token_set.color(value, mode)
    parsed = parse_css_color(value)
    if parsed is None:
        raise ValueError("Cannot parse color or token path %r" % value)
    return parsed


def cmd_contrast(args: argparse.Namespace) -> int:
    token_set = load_token_set(Path(args.tokens), []) if args.tokens else None
    if token_set is not None and token_set.errors:
        for error in token_set.errors:
            print("ERROR: %s" % error, file=sys.stderr)
        return 1
    try:
        foreground = resolve_color_argument(args.foreground, token_set, args.mode)
        background = resolve_color_argument(args.background, token_set, args.mode)
    except ValueError as exc:
        print("ERROR: %s" % exc, file=sys.stderr)
        return 1
    if background[3] < 1:
        print("ERROR: background is translucent; composite it over its real backdrop first", file=sys.stderr)
        return 1
    ratio = contrast_ratio(foreground, background)
    verdict = lambda minimum: "pass" if ratio + 1e-9 >= minimum else "fail"  # noqa: E731
    print("%.2f:1  %s on %s" % (ratio, to_hex(foreground), to_hex(background)))
    print("  text AA 4.5:%s  text AAA 7:%s  large text AA 3:%s  non-text UI 3:%s" % (
        verdict(4.5), verdict(7.0), verdict(3.0), verdict(3.0),
    ))
    return 0 if ratio + 1e-9 >= args.min else 1


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)

    check = sub.add_parser("check", help="Validate tokens and declared contrast pairs")
    check.add_argument("tokens", nargs="?", help="DTCG token JSON file (default: designs/system/tokens.json, else ./tokens.json)")
    check.add_argument("--overlay", action="append", default=[], metavar="MODE=PATH", help="Per-mode override file")
    check.add_argument("--json", action="store_true")
    check.set_defaults(func=cmd_check)

    build = sub.add_parser("build", help="Emit platform outputs")
    build.add_argument("tokens", nargs="?", help="DTCG token JSON file (default: designs/system/tokens.json, else ./tokens.json)")
    build.add_argument("--out", help="Output directory (default: the token file's folder)")
    build.add_argument("--format", default="css", help="Comma-separated: %s" % ",".join(FORMATS))
    build.add_argument("--overlay", action="append", default=[], metavar="MODE=PATH")
    build.add_argument("--prefix", default="", help="CSS custom property prefix")
    build.add_argument("--resolve", action="store_true", help="Inline alias values instead of var() references")
    build.add_argument("--css-name", help="CSS output filename (default tokens.css)")
    build.set_defaults(func=cmd_build)

    ramp = sub.add_parser("ramp", help="Generate an OKLCH ramp for a hue")
    ramp.add_argument("--name", required=True, help="Group name, e.g. accent")
    ramp.add_argument("--hue", type=float, required=True, help="OKLCH hue in degrees")
    ramp.add_argument("--chroma", type=float, default=0.16, help="Peak chroma before sRGB gamut mapping")
    ramp.add_argument("--hue-shift", type=float, default=0.0, help="Degrees of hue drift from lightest to darkest")
    ramp.add_argument("--steps", help="Comma-separated steps (default 50..950)")
    ramp.add_argument("--format", choices=["dtcg", "css"], default="dtcg")
    ramp.set_defaults(func=cmd_ramp)

    contrast = sub.add_parser("contrast", help="WCAG 2 contrast of two colors or token paths")
    contrast.add_argument("foreground")
    contrast.add_argument("background")
    contrast.add_argument("--tokens", help="Resolve token paths from this file")
    contrast.add_argument("--mode", default=DEFAULT_MODE)
    contrast.add_argument("--min", type=float, default=4.5, help="Exit 1 below this ratio")
    contrast.set_defaults(func=cmd_contrast)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(errors="backslashreplace")  # type: ignore[attr-defined]
        except (AttributeError, ValueError):
            pass
    args = build_parser().parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
