def camel_identifier(parts: Sequence[str], reserved: Set[str]) -> str:
    words = [word for part in parts for word in re.split(r"[^A-Za-z0-9]+", part) if word]
    if not words:
        words = ["token"]
    text = words[0][:1].lower() + words[0][1:] + "".join(word[:1].upper() + word[1:] for word in words[1:])
    if text[0].isdigit():
        text = "t" + text
    if text.lower() in reserved:
        text += "Token"
    return text


def snake_identifier(parts: Sequence[str]) -> str:
    text = "_".join(word.lower() for part in parts for word in re.split(r"[^A-Za-z0-9]+", part) if word)
    if not text or not text[0].isalpha():
        text = "t_" + text
    return text


def color_parts(path: str) -> List[str]:
    parts = path.split(".")
    return parts[1:] if len(parts) > 1 and parts[0] in {"color", "colors"} else parts


def dimension_points(value: object) -> Optional[float]:
    number, unit = parse_dimension(value)
    if unit in {"px", "pt", "dp"}:
        return number
    if unit == "rem":
        return number * 16
    return None


def unique(names: Dict[str, str], name: str, path: str, errors: List[str], platform: str) -> None:
    if name in names:
        errors.append("%s: %s and %s both map to identifier %s" % (platform, names[name], path, name))
    names[name] = path


def theme_dark_available(token_set: TokenSet) -> bool:
    return "dark" in token_set.modes()


def build_ios(token_set: TokenSet, output: Path, source_label: str) -> List[Path]:
    written: List[Path] = []
    errors: List[str] = []
    catalog = output / "DesignTokens.xcassets"
    catalog.mkdir(parents=True, exist_ok=True)
    info = {"info": {"author": "xcode", "version": 1}}
    write_text_lf((catalog / "Contents.json"), json.dumps(info, indent=2) + "\n")
    written.append(catalog / "Contents.json")
    palette: List[str] = []
    metrics: List[str] = []
    durations: List[str] = []
    names: Dict[str, str] = {}
    has_dark = theme_dark_available(token_set)
    for path in list(token_set.tokens):
        kind = token_set.token_type(path)
        if kind == "color":
            asset = "-".join(color_parts(path))
            identifier = camel_identifier(color_parts(path), SWIFT_RESERVED)
            unique(names, "Palette." + identifier, path, errors, "ios")
            entries = [colorset_entry(token_set.color(path, DEFAULT_MODE), None)]
            if has_dark:
                entries.append(colorset_entry(token_set.color(path, "dark"), "dark"))
            folder = catalog / (asset + ".colorset")
            folder.mkdir(parents=True, exist_ok=True)
            write_text_lf((folder / "Contents.json"), json.dumps({"colors": entries, "info": info["info"]}, indent=2) + "\n")
            written.append(folder / "Contents.json")
            palette.append('        public static let %s = SwiftUI.Color("%s")' % (identifier, asset))
        elif kind == "dimension":
            points = dimension_points(token_set.resolve(path, DEFAULT_MODE))
            if points is not None:
                identifier = camel_identifier(path.split("."), SWIFT_RESERVED)
                unique(names, "Metrics." + identifier, path, errors, "ios")
                metrics.append("        public static let %s: CGFloat = %s" % (identifier, number_text(points)))
        elif kind == "duration":
            identifier = camel_identifier(path.split("."), SWIFT_RESERVED)
            unique(names, "Durations." + identifier, path, errors, "ios")
            seconds = parse_duration_ms(token_set.resolve(path, DEFAULT_MODE)) / 1000
            durations.append("        public static let %s: TimeInterval = %s" % (identifier, number_text(seconds)))
    if errors:
        raise ValueError("; ".join(errors))
    swift = [
        "// %s" % (GENERATED_NOTE % source_label),
        "// Colors resolve from DesignTokens.xcassets (light and dark appearances).",
        "// Dimensions use points; rem values are converted at 16 pt.",
        "import SwiftUI",
        "",
        "public enum DesignTokens {",
        "    public enum Palette {",
        *palette,
        "    }",
        "",
        "    public enum Metrics {",
        *metrics,
        "    }",
        "",
        "    public enum Durations {",
        *durations,
        "    }",
        "}",
    ]
    swift_path = output / "DesignTokens.swift"
    write_text_lf(swift_path, "\n".join(swift) + "\n")
    written.append(swift_path)
    return written


def colorset_entry(rgba: RGBA, appearance: Optional[str]) -> Dict[str, object]:
    r, g, b, alpha = clamp_rgba(rgba)
    entry: Dict[str, object] = {
        "color": {
            "color-space": "srgb",
            "components": {
                "alpha": "%.3f" % alpha,
                "blue": "0x%02X" % int(round(b * 255)),
                "green": "0x%02X" % int(round(g * 255)),
                "red": "0x%02X" % int(round(r * 255)),
            },
        },
        "idiom": "universal",
    }
    if appearance:
        entry = {"appearances": [{"appearance": "luminosity", "value": appearance}], **entry}
    return entry


def android_color(rgba: RGBA) -> str:
    r, g, b, alpha = clamp_rgba(rgba)
    return "#%02X%02X%02X%02X" % tuple(int(round(value * 255)) for value in (alpha, r, g, b))


def xml_escape(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def is_font_size(path: str) -> bool:
    lowered = path.lower()
    return ("font" in lowered or "text" in lowered or "type" in lowered) and "size" in lowered


def build_android(token_set: TokenSet, output: Path, source_label: str) -> List[Path]:
    errors: List[str] = []
    names: Dict[str, str] = {}
    colors_day: List[str] = []
    colors_night: List[str] = []
    dimens: List[str] = []
    integers: List[str] = []
    has_dark = theme_dark_available(token_set)
    for path in list(token_set.tokens):
        kind = token_set.token_type(path)
        if kind == "color":
            name = snake_identifier(color_parts(path))
            unique(names, "color/" + name, path, errors, "android")
            day = token_set.color(path, DEFAULT_MODE)
            colors_day.append('    <color name="%s">%s</color>' % (name, android_color(day)))
            if has_dark:
                night = token_set.color(path, "dark")
                if android_color(night) != android_color(day):
                    colors_night.append('    <color name="%s">%s</color>' % (name, android_color(night)))
        elif kind == "dimension":
            points = dimension_points(token_set.resolve(path, DEFAULT_MODE))
            if points is not None:
                name = snake_identifier(path.split("."))
                unique(names, "dimen/" + name, path, errors, "android")
                dimens.append('    <dimen name="%s">%s%s</dimen>' % (name, number_text(points), "sp" if is_font_size(path) else "dp"))
        elif kind == "duration":
            name = snake_identifier(path.split("."))
            unique(names, "integer/" + name, path, errors, "android")
            integers.append('    <integer name="%s">%d</integer>' % (name, int(round(parse_duration_ms(token_set.resolve(path, DEFAULT_MODE))))))
    if errors:
        raise ValueError("; ".join(errors))
    written: List[Path] = []
    header = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- %s -->" % xml_escape(GENERATED_NOTE % source_label), "<resources>"]
    for relative, body in (
        ("values/colors.xml", colors_day),
        ("values-night/colors.xml", colors_night if has_dark else []),
        ("values/dimens.xml", dimens),
        ("values/integers.xml", integers),
    ):
        if not body:
            continue
        target = output / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        write_text_lf(target, "\n".join(header + body + ["</resources>"]) + "\n")
        written.append(target)
    return written


def pascal(text: str) -> str:
    return "".join(word[:1].upper() + word[1:] for word in re.split(r"[^A-Za-z0-9]+", text) if word)


def build_flutter(token_set: TokenSet, output: Path, source_label: str) -> List[Path]:
    errors: List[str] = []
    lines = [
        "// %s" % (GENERATED_NOTE % source_label),
        "// Dimensions are logical pixels; rem values are converted at 16.",
        "import 'dart:ui' show Color;",
        "",
    ]
    themes = theme_modes(token_set)
    for mode in themes:
        class_name = "DesignColors" + ("" if mode == DEFAULT_MODE else pascal(mode))
        names: Dict[str, str] = {}
        body: List[str] = []
        for path in list(token_set.tokens):
            if token_set.token_type(path) != "color":
                continue
            identifier = camel_identifier(color_parts(path), DART_RESERVED)
            unique(names, identifier, path, errors, "flutter")
            argb = android_color(token_set.color(path, mode)).lstrip("#")
            body.append("  static const Color %s = Color(0x%s);" % (identifier, argb))
        if body:
            label = "default" if mode == DEFAULT_MODE else mode
            lines += ["/// Color tokens for the %s mode." % label, "class %s {" % class_name, "  const %s._();" % class_name, *body, "}", ""]
    metric_names: Dict[str, str] = {}
    metrics: List[str] = []
    durations: List[str] = []
    for path in list(token_set.tokens):
        kind = token_set.token_type(path)
        if kind == "dimension":
            points = dimension_points(token_set.resolve(path, DEFAULT_MODE))
            if points is not None:
                identifier = camel_identifier(path.split("."), DART_RESERVED)
                unique(metric_names, identifier, path, errors, "flutter")
                metrics.append("  static const double %s = %s;" % (identifier, "%.1f" % points if points == int(points) else number_text(points)))
        elif kind == "duration":
            identifier = camel_identifier(path.split("."), DART_RESERVED)
            unique(metric_names, identifier, path, errors, "flutter")
            durations.append("  static const Duration %s = Duration(milliseconds: %d);" % (identifier, int(round(parse_duration_ms(token_set.resolve(path, DEFAULT_MODE))))))
    if errors:
        raise ValueError("; ".join(errors))
    if metrics:
        lines += ["/// Spacing, radius and size tokens in logical pixels.", "class DesignMetrics {", "  const DesignMetrics._();", *metrics, "}", ""]
    if durations:
        lines += ["/// Motion duration tokens.", "class DesignDurations {", "  const DesignDurations._();", *durations, "}", ""]
    output.mkdir(parents=True, exist_ok=True)
    target = output / "design_tokens.dart"
    write_text_lf(target, "\n".join(lines).rstrip() + "\n")
    return [target]


FORMATS = ("css", "json", "ios", "android", "flutter")


def build_tokens(path: Path, output: Path, formats: Sequence[str], overlays: Sequence[str] = (), prefix: str = "", resolve_aliases: bool = False, css_name_override: Optional[str] = None) -> Tuple[List[Path], Dict[str, object]]:
    report = check_tokens(path, overlays)
    if report["errors"]:
        return [], report
    token_set = load_token_set(path, overlays)
    label = path.name
    written: List[Path] = []
    output.mkdir(parents=True, exist_ok=True)
    for fmt in formats:
        if fmt == "css":
            target = output / (css_name_override or "tokens.css")
            write_text_lf(target, build_css(token_set, label, prefix, resolve_aliases))
            written.append(target)
        elif fmt == "json":
            target = output / "tokens.resolved.json"
            write_text_lf(target, build_json(token_set, label))
            written.append(target)
        elif fmt == "ios":
            written.extend(build_ios(token_set, output / "ios", label))
        elif fmt == "android":
            written.extend(build_android(token_set, output / "android", label))
        elif fmt == "flutter":
            written.extend(build_flutter(token_set, output / "flutter", label))
        else:
            raise ValueError("Unknown format %r; choose from %s" % (fmt, ", ".join(FORMATS)))
    return written, report


